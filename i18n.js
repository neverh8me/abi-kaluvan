  if (!DICT[lang]) lang = 'uk';

  function t(key, vars) {
    let s = DICT[lang][key] ?? DICT.uk[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
    return s;
  }

